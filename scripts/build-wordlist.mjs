// Turns data/words.txt into a TypeScript module so the word list is bundled
// into the app's JavaScript and a round works without fetching anything.
// Runs automatically after `npm install` (see "postinstall" in package.json).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const source = new URL('../data/words.txt', import.meta.url);
const outDir = new URL('../src/data/', import.meta.url);

const text = readFileSync(source, 'utf8');
mkdirSync(outDir, { recursive: true });
writeFileSync(
  new URL('words.generated.ts', outDir),
  `// Generated by scripts/build-wordlist.mjs from data/words.txt. Do not edit.\n` +
    `export const WORDS_TEXT = ${JSON.stringify(text)};\n`,
);
console.log(`Wrote src/data/words.generated.ts (${text.split('\n').length} lines)`);
